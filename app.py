from flask import Flask, render_template, request, jsonify
import requests
import os

app = Flask(__name__)

# Ollama configuration
OLLAMA_URL = "http://localhost:11434/api/generate"
MODEL = "llama3.2"


# Function to communicate with Ollama
def ask_ollama(prompt):

    data = {
        "model": MODEL,
        "prompt": prompt,
        "stream": False
    }

    try:
        response = requests.post(
            OLLAMA_URL,
            json=data,
            timeout=180
        )

        response.raise_for_status()

        return response.json()["response"]

    except Exception as e:

        return f"Ollama Error: {e}"


# Home page
@app.route("/")
def home():

    return render_template("index.html")


# Generate Blog
@app.route("/generate_blog", methods=["POST"])
def generate_blog():

    data = request.json

    topic = data["topic"]
    style = data["style"]
    tone = data["tone"]
    word_count = data["word_count"]

    prompt = f"""
Write a high-quality blog about:

Topic: {topic}

Writing Style: {style}

Tone: {tone}

Approximate Word Count: {word_count}

Requirements:
1. Give an attractive title.
2. Write an introduction.
3. Use suitable headings and subheadings.
4. Explain the topic clearly.
5. Include examples where appropriate.
6. End with a conclusion.
7. Do not mention that the content was generated by AI.

Return only the blog.
"""

    blog = ask_ollama(prompt)

    # Save blog
    os.makedirs("outputs", exist_ok=True)

    with open(
        "outputs/generated_blog.txt",
        "w",
        encoding="utf-8"
    ) as file:

        file.write(blog)

    return jsonify({
        "blog": blog
    })



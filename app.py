# Intent Detection
@app.route("/detect_intent", methods=["POST"])
def detect_intent():

    data = request.json

    user_input = data["text"]

    prompt = f"""
You are an intent detection system.

Classify the following user request into exactly
one of these categories:

BLOG_GENERATION
SUMMARY
KEYWORD_GENERATION
META_DESCRIPTION

User request:
{user_input}

Return ONLY the category name.
"""

    result = ask_ollama(prompt).strip().upper()

    if "BLOG_GENERATION" in result:
        intent = "BLOG_GENERATION"

    elif "SUMMARY" in result:
        intent = "SUMMARY"

    elif "KEYWORD_GENERATION" in result:
        intent = "KEYWORD_GENERATION"

    elif "META_DESCRIPTION" in result:
        intent = "META_DESCRIPTION"

    else:
        intent = "UNKNOWN"

    return jsonify({
        "intent": intent
    })


